import { Invoice, PrintReceiptOptions } from '@invodesk/types';
import { EscPosEncoder } from './encoder.js';

export interface ReceiptBusinessDetails {
  storeName: string;
  branchName: string;
  gstin?: string;
  phone: string;
  address: string;
  termsMessage?: string;
}

/**
 * High-performance ESC/POS thermal receipt formatter for retail checkouts
 */
export function formatThermalReceipt(
  invoice: Invoice,
  business: ReceiptBusinessDetails,
  options: PrintReceiptOptions
): Uint8Array {
  const encoder = new EscPosEncoder(options.paperWidth);

  // 1. Optional Cash Drawer Kick Pulse before or on print
  if (options.openDrawer) {
    encoder.kickCashDrawer(2);
  }

  // 2. Store Header
  encoder.alignCenter();
  encoder.bold(true);
  encoder.doubleSize(true);
  encoder.line(business.storeName);
  encoder.doubleSize(false);
  encoder.bold(false);

  if (business.branchName) {
    encoder.line(business.branchName);
  }
  if (business.address) {
    encoder.line(business.address);
  }
  if (business.phone) {
    encoder.line(`Tel: ${business.phone}`);
  }
  if (business.gstin) {
    encoder.bold(true);
    encoder.line(`GSTIN: ${business.gstin}`);
    encoder.bold(false);
  }

  encoder.separator('=');

  // 3. Invoice Meta
  encoder.alignLeft();
  encoder.twoColumns('Tax Invoice', invoice.invoiceNumber);
  encoder.twoColumns('Date:', new Date(invoice.createdAt).toLocaleString('en-IN', { timeZone: 'Asia/Kolkata' }));
  if (invoice.customerName && invoice.customerName !== 'Retail Customer') {
    encoder.twoColumns('Customer:', invoice.customerName);
  }
  if (invoice.customerGstin) {
    encoder.twoColumns('Cust GSTIN:', invoice.customerGstin);
  }

  encoder.separator('-');

  // 4. Line Items Table Header
  if (options.paperWidth === '80mm') {
    encoder.bold(true);
    // 22 + 6 + 10 + 10 = 48 chars
    encoder.line('ITEM                  QTY      RATE     TOTAL');
    encoder.bold(false);
    encoder.separator('-');
  }

  // Line Items
  for (const item of invoice.items) {
    encoder.itemRow(item.name, item.quantity, item.unitPrice, item.totalAmount);
  }

  encoder.separator('-');

  // 5. Financial Breakdown
  encoder.twoColumns('Sub Total:', invoice.subTotal.toFixed(2));
  if (invoice.totalDiscount > 0) {
    encoder.twoColumns('Discount:', `-${invoice.totalDiscount.toFixed(2)}`);
  }
  encoder.twoColumns('Taxable Amount:', invoice.taxableAmount.toFixed(2));

  // GST Breakdown
  if (invoice.totalCgst > 0) {
    encoder.twoColumns('CGST:', invoice.totalCgst.toFixed(2));
  }
  if (invoice.totalSgst > 0) {
    encoder.twoColumns('SGST:', invoice.totalSgst.toFixed(2));
  }
  if (invoice.totalIgst > 0) {
    encoder.twoColumns('IGST:', invoice.totalIgst.toFixed(2));
  }
  if (invoice.totalCess > 0) {
    encoder.twoColumns('Cess:', invoice.totalCess.toFixed(2));
  }
  if (invoice.roundOff !== undefined && invoice.roundOff !== null && invoice.roundOff !== 0) {
    encoder.twoColumns('Round Off:', invoice.roundOff > 0 ? `+${invoice.roundOff.toFixed(2)}` : invoice.roundOff.toFixed(2));
  }

  encoder.separator('=');

  // 6. Grand Total
  encoder.bold(true);
  encoder.doubleSize(true);
  encoder.twoColumns('GRAND TOTAL:', `Rs.${invoice.grandTotal.toFixed(2)}`);
  encoder.doubleSize(false);
  encoder.bold(false);

  encoder.separator('-');

  // 7. Payment Modes
  if (invoice.payments && invoice.payments.length > 0) {
    encoder.bold(true);
    encoder.line('PAYMENT DETAILS:');
    encoder.bold(false);
    for (const p of invoice.payments) {
      encoder.twoColumns(
        `  ${p.mode}${p.referenceNumber ? ` (${p.referenceNumber})` : ''}`,
        `Rs.${p.amount.toFixed(2)}`
      );
    }
  }

  if (invoice.balanceAmount > 0) {
    encoder.bold(true);
    encoder.twoColumns('BALANCE DUE (KHATA):', `Rs.${invoice.balanceAmount.toFixed(2)}`);
    encoder.bold(false);
  }

  encoder.separator('-');

  // 8. Footer & Barcode
  if (options.barcodeQr !== false && invoice.invoiceNumber) {
    encoder.barcode(invoice.invoiceNumber);
  }

  encoder.alignCenter();
  encoder.line(business.termsMessage || 'Thank you for shopping with us!');
  encoder.line('GST invoice generated by InvoDesk');

  // 9. Cut
  if (options.cutPaper !== false) {
    encoder.cut(true);
  }

  return encoder.encode();
}
